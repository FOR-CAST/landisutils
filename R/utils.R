#' Format a vector of keyword names for inline `roxygen2` use
#'
#' Wraps each element in backticks (so `roxygen2` markdown renders each
#' key as `\code{}` in the generated `.Rd`, which also keeps these
#' identifiers out of `spelling::spell_check_package()`) and joins with
#' `, `. Intended for inline expansion via `` `r .fmtKeys(.someKeys)` ``
#' so users see the literal allowed values in the rendered manual rather
#' than a reference to a non-exported internal vector.
#'
#' @param x Character vector of keyword names.
#'
#' @return A single character string.
#'
#' @keywords internal
.fmtKeys <- function(x) {
  paste(sprintf("`%s`", x), collapse = ", ")
}

#' Require an optional (`Suggests`) package, with an actionable error
#'
#' Several capabilities here rest on packages that most users of this one never
#' touch: reading Arrow datasets, drawing plots, recomputing fire weather. Those
#' live in `Suggests` rather than `Imports` so installing this package does not
#' drag them in -- `arrow` alone is 99 MB, and `cffdrs` pulls 16 packages nothing
#' else needs. Call this at the top of any exported function that reaches one, so
#' a missing package produces a message naming what to install rather than a bare
#' "there is no package called ..." from somewhere deep in the call stack.
#'
#' @param pkg Character. The package needed.
#' @param what Character. What the caller was trying to do, phrased to read after
#'   a subject: `"Reading a parquet dataset"`.
#'
#' @return Invisibly `TRUE`; called for its side effect of stopping.
#'
#' @keywords internal
.need <- function(pkg, what) {
  missing <- pkg[!vapply(pkg, requireNamespace, logical(1), quietly = TRUE)]
  if (length(missing) > 0L) {
    stop(
      what,
      " requires the ",
      paste(sprintf("'%s'", missing), collapse = " and "),
      if (length(missing) > 1L) " packages." else " package.",
      "\nInstall with: install.packages(",
      if (length(missing) > 1L) {
        paste0("c(", paste(sprintf('"%s"', missing), collapse = ", "), ")")
      } else {
        sprintf('"%s"', missing)
      },
      ")",
      call. = FALSE
    )
  }
  invisible(TRUE)
}

#' @keywords internal
.checkPath <- function(path) {
  path <- fs::path_norm(path) |> fs::dir_create()

  return(path)
}

#' @keywords internal
.relPath <- function(path, start = ".") {
  if (is.null(path)) {
    return(NULL)
  }
  vapply(
    path,
    function(p) if (is.na(p)) NA_character_ else fs::path_rel(p, start),
    character(1),
    USE.NAMES = FALSE
  )
}

#' @keywords internal
landisutilsVersion <- function() {
  packageVersion("landisutils")
}

#' @keywords internal
landisutilsHeader <- function() {
  ## NB: NO timestamp here. Generated files must be byte-reproducible so that
  ## tar_landis()'s input-hash skip-check is stable across re-writes of an
  ## unchanged scenario -- a timestamp would change the hash on every Phase-3
  ## rebuild and needlessly re-run every replicate. The package version is kept:
  ## an intentional landisutils bump legitimately invalidates reps.
  c(
    glue::glue(">> generated by `landisutils` (v{landisutilsVersion()})"),
    glue::glue(">> do not edit by hand; manual changes to this file may be overwritten"),
    glue::glue("")
  )
}

#' Write a LANDIS-II `LandisData` header block
#'
#' Emits the `landisutils` auto-generated file header followed by the
#' `LandisData  "<x>"` line and a blank line. Every LANDIS-II input file
#' starts with this block.
#'
#' @param x Character. The `LandisData` value (extension or scenario name).
#'
#' @template return_insert
#'
#' @export
insertLandisData <- function(x) {
  c(landisutilsHeader(), glue::glue("LandisData  \"{x}\""), glue::glue(""))
}

#' Specify an input parameter value for an extension
#'
#' @param type Character, specifying the parameter type (i.e., the LANDIS-II name for the input).
#'
#' @param value A single parameter value of integer, numeric, or character type.
#'
#' @param blank_line Logical. Should a blank line be added after the line?
#'
#' @template return_insert
#'
#' @export
insertValue <- function(type, value, blank_line = TRUE) {
  stopifnot(length(value) == 1)

  if (!is.na(value)) {
    if (is.character(value)) {
      ## LANDIS-II's parser only accepts double-quoted strings when the value contains whitespace;
      ## bare tokens (yes/no, enum values, paths without spaces) must be emitted unquoted.
      if (grepl("[[:space:]]", value)) {
        out <- glue::glue("{type}    \"{value}\"")
      } else {
        out <- glue::glue("{type}    {value}")
      }
    } else {
      out <- glue::glue("{type}    {format(value, digits = 8, scientific = FALSE)}")
    }

    if (isTRUE(blank_line)) {
      out <- c(out, glue::glue(""))
    }
  } else {
    out <- ""
  }

  out
}

#' Specify an input file for an extension
#'
#' Emits a `<type>  <file>` line. `NULL` (and length-zero) input is treated
#' as "parameter omitted" and produces no output, matching how
#' [insertValue()] handles `NA`.
#'
#' @param type Character, specifying the parameter type (i.e., the LANDIS-II name for the input).
#'
#' @template param_file
#'
#' @template return_insert
#'
#' @export
insertFile <- function(type, file) {
  if (is.null(file) || length(file) == 0L) {
    return("")
  }

  insertValue(type, file)
}

#' Convert logical to a LANDIS-II yes/no or true/false token
#'
#' LANDIS-II input files mostly use the strings `"yes"` and `"no"` for
#' boolean parameters, but a few extensions (e.g. Magic Harvest's
#' `NoHarvestReInitialization`) require `"true"` / `"false"` instead.
#'
#' @param x one of `TRUE`, `FALSE`, `"Y"`, `"N"`, `"yes"`, `"no"`,
#'   `"T"`, `"F"`, `"true"`, `"false"` (case-insensitive).
#'
#' @return
#' - `yesno()`: character `"yes"` or `"no"`.
#' - `truefalse()`: character `"true"` or `"false"`.
#'
#' @export
#' @rdname yesno
yesno <- function(x) {
  stopifnot(
    "x must be one of TRUE, FALSE, 'Y', 'N', 'yes', or 'no'." = length(x) == 1 &&
      !is.null(x) &&
      !is.na(x)
  )

  if (is.character(x)) {
    x <- tolower(x)

    if (x %in% c("yes", "y", "true", "t")) {
      x <- TRUE
    } else if (x %in% c("no", "n", "false", "f")) {
      x <- FALSE
    } else {
      stop("x must be one of TRUE, FALSE, 'Y', 'N', 'yes', 'no', 'true', or 'false'.")
    }
  }

  ifelse(isTRUE(x), "yes", "no")
}

#' @export
#' @rdname yesno
truefalse <- function(x) {
  ifelse(yesno(x) == "yes", "true", "false")
}

## Drop the Dynamic Fire summary log's initial timestep.
##
## The summary log reports Time 0 -- the landscape's initial state, written before any disturbance
## -- and it necessarily carries zero fires. Left in, `n_fires_by_year` has `sim_years + 1` rows and
## that row does damage twice: it is a spurious year in every rate denominator (understating the
## simulated annual rate by sim_years/(sim_years+1), which is 9% on a 10-year trial), and a spurious
## zero in every plotted distribution. The plotting harm scales with how far a zero sits from the
## mean, so it is worst exactly where the fire regime is most active: on a landscape averaging ~28
## fires/yr one such zero per replicate cut the plotted standard deviation nearly in half.
##
## Applied at the parser so the row never reaches a consumer, AND defensively in the consumers, so
## that summaries CACHED before this fix are corrected on read rather than silently scoring wrong.
## Idempotent: filtering a table that has no Time 0 row is a no-op.
.drop_initial_timestep <- function(x) {
  if (is.null(x) || !is.data.frame(x) || nrow(x) == 0L || !("year" %in% names(x))) {
    return(x)
  }
  x[!is.na(x$year) & x$year > 0L, , drop = FALSE]
}

